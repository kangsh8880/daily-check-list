create table if not exists i18n_strings (
  str_key      text primary key,
  category     text not null default 'common',
  ko           text not null,
  en           text,
  vi           text,
  updated_at   timestamptz not null default now()
);

alter table i18n_strings enable row level security;

drop policy if exists i18n_strings_select on i18n_strings;
create policy i18n_strings_select on i18n_strings for select using (true);

revoke insert, update, delete on i18n_strings from anon, authenticated;
grant select on i18n_strings to anon, authenticated;

-- 관리자 화면(다국어 관리)에서 특정 언어 번역 1건 수정
create or replace function fn_update_i18n_lang(p_key text, p_lang text, p_text text)
returns void language plpgsql security definer as $$
begin
  if p_lang = 'en' then
    update i18n_strings set en = p_text, updated_at = now() where str_key = p_key;
  elsif p_lang = 'vi' then
    update i18n_strings set vi = p_text, updated_at = now() where str_key = p_key;
  elsif p_lang = 'ko' then
    update i18n_strings set ko = p_text, updated_at = now() where str_key = p_key;
  end if;
end;
$$;

-- 특정 키를 시드 기본값으로 되돌릴 때 사용 (다국어 관리 화면의 "기본값으로 초기화")
create or replace function fn_upsert_i18n_string(p_key text, p_category text, p_ko text, p_en text, p_vi text)
returns void language plpgsql security definer as $$
begin
  insert into i18n_strings(str_key, category, ko, en, vi, updated_at)
    values (p_key, coalesce(p_category,'common'), p_ko, p_en, p_vi, now())
  on conflict (str_key) do update set
    category = excluded.category, ko = excluded.ko, en = excluded.en, vi = excluded.vi, updated_at = now();
end;
$$;

grant execute on all functions in schema public to anon, authenticated;

